// Pure configuration logic for the project initializer: validation, defaults,
// .env rendering and the edits to known metadata fields. Nothing here touches
// the filesystem, the network or the terminal, so it is easy to test and can
// be reused by a standalone `create-*` CLI later.
import { randomBytes } from "node:crypto"

export const TEMPLATE_NAME = "web-starter"
export const TEMPLATE_DISPLAY_NAME = "Web Starter"
const NEXT_DEFAULT_TITLE = "Create Next App"
const NEXT_DEFAULT_DESCRIPTION = "Generated by create next app"

export const DEFAULT_PORTS = { port: 3000, dbPort: 5432, studioPort: 5555 }
export const MIN_PORT = 1024
export const MAX_PORT = 65535

// ---------------------------------------------------------------------------
// Names

/** "My Inventory App!" -> "my-inventory-app" */
export function slugify(value) {
  return String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 50)
    .replace(/-+$/, "")
}

/** "inventory-app" -> "inventory_app", safe as a Postgres identifier. */
export function toIdentifier(value) {
  let id = String(value).toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "")
  if (!/^[a-z_]/.test(id)) id = `app_${id}`
  return id.slice(0, 63)
}

/** "inventory-app" -> "Inventory App" */
export function toDisplayName(slug) {
  return String(slug)
    .split(/[-_.\s]+/)
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ")
}

/** Defaults that follow from the project name. */
export function deriveDefaults(projectName) {
  return {
    displayName: toDisplayName(projectName),
    composeProjectName: projectName,
    dbName: toIdentifier(projectName),
    dbUser: toIdentifier(projectName),
  }
}

export function generatePassword() {
  // 32 URL-safe characters: no quoting or escaping needed anywhere.
  return randomBytes(24).toString("base64url")
}

// ---------------------------------------------------------------------------
// Validation. Each validator returns an error message, or undefined when valid.

export function validateProjectName(value) {
  if (!value) return "Enter a project name."
  if (value.length > 50) return "Use at most 50 characters."
  if (!/^[a-z0-9]([a-z0-9-]*[a-z0-9])?$/.test(value)) {
    return "Use lowercase letters, digits and dashes, starting and ending with a letter or digit (e.g. inventory-app)."
  }
}

export function validateDisplayName(value) {
  if (!value || !value.trim()) return "Enter a display name."
  if (value.length > 60) return "Use at most 60 characters."
  if (/[\r\n]/.test(value)) return "Use a single line."
}

export function validateComposeProjectName(value) {
  if (!value) return "Enter a Docker Compose project name."
  if (value.length > 50) return "Use at most 50 characters."
  // Docker Compose's own rule for project names.
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(value)) {
    return "Use lowercase letters, digits, dashes and underscores, starting with a letter or digit."
  }
}

export function validateIdentifier(value, label = "name") {
  if (!value) return `Enter a ${label}.`
  if (!/^[a-z_][a-z0-9_]{0,62}$/.test(value)) {
    return `Use up to 63 lowercase letters, digits and underscores, starting with a letter or underscore.`
  }
}

export function validatePassword(value) {
  if (!value) return "Enter a password."
  if (value.length < 12) return "Use at least 12 characters."
  if (value.length > 128) return "Use at most 128 characters."
  return validatePasswordFormat(value)
}

function validatePasswordFormat(value) {
  if (!value) return "Enter a password."
  // A single quote can't be written inside the single-quoted .env value; a
  // newline can't be written at all.
  if (/['\r\n]/.test(value)) return "Single quotes and line breaks aren't supported."
}

/** Parses a port answer. Returns { port } or { error }. */
export function parsePort(value) {
  const text = String(value).trim()
  if (!/^\d+$/.test(text)) return { error: "Enter a number." }
  const port = Number(text)
  if (port < MIN_PORT || port > MAX_PORT) {
    return { error: `Use a port between ${MIN_PORT} and ${MAX_PORT}.` }
  }
  return { port }
}

/** Ports must be distinct within one project. Returns an error message or undefined. */
export function findDuplicatePorts(ports) {
  const seen = new Map()
  for (const [label, port] of Object.entries(ports)) {
    if (port === undefined) continue
    if (seen.has(port)) return `Port ${port} is chosen for both ${seen.get(port)} and ${label}.`
    seen.set(port, label)
  }
}

/** Validates a complete set of answers. Returns a list of error messages. */
export function validateAnswers(answers) {
  const errors = [
    validateProjectName(answers.projectName),
    validateDisplayName(answers.displayName),
    validateComposeProjectName(answers.composeProjectName),
    validateIdentifier(answers.dbName, "database name"),
    validateIdentifier(answers.dbUser, "database username"),
    // A password kept from an existing database only has to be writable.
    answers.keepPassword ? validatePasswordFormat(answers.dbPassword) : validatePassword(answers.dbPassword),
  ]
  for (const key of ["port", "dbPort", "studioPort"]) {
    const { error } = parsePort(answers[key])
    if (error) errors.push(`${key}: ${error}`)
  }
  errors.push(
    findDuplicatePorts({
      "the app": answers.port,
      PostgreSQL: answers.dbPort,
      "Prisma Studio": answers.studioPort,
    })
  )
  return errors.filter(Boolean)
}

// ---------------------------------------------------------------------------
// Connection URLs

export function databaseUrl({ user, password, host, port, name, schema }) {
  const auth = `${encodeURIComponent(user)}:${encodeURIComponent(password)}`
  const query = schema ? `?schema=${encodeURIComponent(schema)}` : ""
  return `postgresql://${auth}@${host}:${port}/${encodeURIComponent(name)}${query}`
}

// ---------------------------------------------------------------------------
// .env files. The format is the common subset that Docker Compose, Node's
// process.loadEnvFile and Next.js all read the same way: KEY=value, with
// anything beyond plain characters wrapped in single quotes, which all three
// take literally (no $ interpolation, no # comments).

const KEY_LINE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/

export function formatEnvValue(value) {
  const text = String(value)
  if (/^[A-Za-z0-9_\-.:/@?=&%+,]*$/.test(text)) return text
  if (/['\r\n]/.test(text)) throw new Error("Values with single quotes or line breaks can't be written to .env")
  return `'${text}'`
}

function parseEnvValue(raw) {
  const value = raw.trim()
  const quote = value[0]
  if (quote === "'" || quote === '"' || quote === "`") {
    const end = value.indexOf(quote, 1)
    if (end > 0) {
      const inner = value.slice(1, end)
      return quote === '"' ? inner.replace(/\\n/g, "\n") : inner
    }
  }
  // Unquoted: an inline comment starts at " #".
  return value.replace(/\s+#.*$/, "")
}

/** Parses .env text into an ordered { key: value } object. */
export function parseEnv(text) {
  const values = {}
  for (const line of String(text).split(/\r?\n/)) {
    if (/^\s*#/.test(line)) continue
    const match = line.match(KEY_LINE)
    if (match) values[match[1]] = parseEnvValue(match[2])
  }
  return values
}

/**
 * Renders .env from the documented template: keeps its comments and order,
 * fills in `values`, and appends `extras` (variables from an earlier .env that
 * the template doesn't know) so nothing the app relies on is lost.
 */
export function renderEnv(template, values, extras = {}) {
  const used = new Set()
  const lines = String(template)
    .replace(/\n$/, "")
    .split("\n")
    .map((line) => {
      if (/^\s*#/.test(line)) return line
      const match = line.match(KEY_LINE)
      if (!match) return line
      const key = match[1]
      used.add(key)
      if (key in values) return `${key}=${formatEnvValue(values[key])}`
      if (key in extras) return `${key}=${formatEnvValue(extras[key])}`
      return line
    })
  const rest = Object.entries(extras).filter(([key]) => !used.has(key) && !(key in values))
  if (rest.length) {
    lines.push("", "# Other variables, kept from your previous .env")
    for (const [key, value] of rest) lines.push(`${key}=${formatEnvValue(value)}`)
  }
  return lines.join("\n") + "\n"
}

/** The .env values that setup owns, computed from the answers. */
export function buildEnvValues(answers, previous = {}) {
  const schema = previous.DB_SCHEMA || answers.dbSchema || "app"
  const db = { user: answers.dbUser, password: answers.dbPassword, name: answers.dbName, schema }
  // Follow the port only while the app URL is still a localhost address; keep
  // a real domain someone set by hand.
  const previousUrl = previous.NEXT_PUBLIC_APP_URL
  const appUrl =
    !previousUrl || /^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?\/?$/.test(previousUrl)
      ? `http://localhost:${answers.port}`
      : previousUrl
  return {
    COMPOSE_PROJECT_NAME: answers.composeProjectName,
    PORT: String(answers.port),
    NEXT_PUBLIC_APP_URL: appUrl,
    DB_HOST: "localhost",
    DB_PORT: String(answers.dbPort),
    DB_NAME: answers.dbName,
    DB_USER: answers.dbUser,
    DB_PASSWORD: answers.dbPassword,
    DB_SCHEMA: schema,
    DATABASE_URL: databaseUrl({ ...db, host: "localhost", port: answers.dbPort }),
    DOCKER_DATABASE_URL: databaseUrl({ ...db, host: "db", port: 5432 }),
    STUDIO_PORT: String(answers.studioPort),
    COMPOSE_PROFILES: answers.enableStudio ? "tools" : "",
  }
}

// ---------------------------------------------------------------------------
// Known metadata fields. Each edit changes one field and returns the text
// unchanged when the field isn't in the expected shape.

function editJson(text, edit) {
  const data = JSON.parse(text)
  edit(data)
  return JSON.stringify(data, null, 2) + "\n"
}

export function updatePackageJson(text, name) {
  return editJson(text, (data) => {
    data.name = name
  })
}

export function updatePackageLock(text, name) {
  return editJson(text, (data) => {
    data.name = name
    if (data.packages?.[""]) data.packages[""].name = name
  })
}

export function updateLaunchJson(text, { port, studioPort }) {
  return editJson(text, (data) => {
    for (const config of data.configurations ?? []) {
      if (config.name === "dev") config.port = Number(port)
      if (config.name === "studio") config.port = Number(studioPort)
    }
  })
}

const STRING_LITERAL = String.raw`"(?:[^"\\\n]|\\.)*"`

function metadataBlock(text) {
  return text.match(/export const metadata(?::\s*Metadata)?\s*=\s*\{[\s\S]*?\n\};?/)
}

/** The current `title` in app/layout.tsx metadata, if it's a plain string. */
export function readLayoutTitle(text) {
  const block = metadataBlock(text)
  const match = block?.[0].match(new RegExp(String.raw`\n\s*title:\s*(${STRING_LITERAL})`))
  return match ? JSON.parse(match[1]) : undefined
}

/** Sets the metadata title; replaces the description only while it's create-next-app's default. */
export function updateLayoutMetadata(text, displayName) {
  const block = metadataBlock(text)
  if (!block) return text
  const updated = block[0]
    .replace(
      new RegExp(String.raw`(\n\s*title:\s*)${STRING_LITERAL}`),
      (_, prefix) => prefix + JSON.stringify(displayName)
    )
    .replace(
      new RegExp(String.raw`(\n\s*description:\s*)${JSON.stringify(NEXT_DEFAULT_DESCRIPTION)}`),
      (_, prefix) => prefix + JSON.stringify(displayName)
    )
  return text.replace(block[0], () => updated)
}

/** Renames the README heading while it's still the template's, or the previous display name. */
export function updateReadmeHeading(text, displayName, previousDisplayName) {
  const known = new Set([TEMPLATE_DISPLAY_NAME, previousDisplayName].filter(Boolean))
  const firstLine = text.split("\n", 1)[0]
  const heading = firstLine.replace(/^#\s+/, "")
  if (!firstLine.startsWith("# ") || !known.has(heading)) return text
  return `# ${displayName}` + text.slice(firstLine.length)
}

export function isTemplateTitle(title) {
  return !title || title === NEXT_DEFAULT_TITLE || title === TEMPLATE_DISPLAY_NAME
}

// ---------------------------------------------------------------------------
// The plan: every file setup writes, computed up front so nothing is written
// unless all of it can be.

/**
 * @param answers validated answers
 * @param files { [path]: current text | undefined }, for .env.example, .env,
 *   package.json, package-lock.json, app/layout.tsx, README.md, .claude/launch.json
 * @returns [{ path, before, after }] for the files that change
 */
export function planChanges(answers, files) {
  const previousEnv = files[".env"] ? parseEnv(files[".env"]) : {}
  const values = buildEnvValues(answers, previousEnv)
  const template = files[".env.example"]
  if (!template) throw new Error(".env.example is missing; it's the template .env is generated from.")
  // Everything else from the earlier .env is kept as it was: template keys
  // setup doesn't own (e.g. DB_POOL_MAX) and variables the template doesn't know.
  const extras = Object.fromEntries(Object.entries(previousEnv).filter(([key]) => !(key in values)))
  const previousTitle = files["app/layout.tsx"] ? readLayoutTitle(files["app/layout.tsx"]) : undefined
  const edits = {
    ".env": () => renderEnv(template, values, extras),
    "package.json": (text) => updatePackageJson(text, answers.projectName),
    "package-lock.json": (text) => updatePackageLock(text, answers.projectName),
    "app/layout.tsx": (text) => updateLayoutMetadata(text, answers.displayName),
    "README.md": (text) => updateReadmeHeading(text, answers.displayName, previousTitle),
    ".claude/launch.json": (text) => updateLaunchJson(text, answers),
  }

  const changes = []
  for (const [path, edit] of Object.entries(edits)) {
    const before = files[path]
    if (before === undefined && path !== ".env") continue
    const after = edit(before)
    if (after !== before) changes.push({ path, before, after })
  }
  return changes
}
